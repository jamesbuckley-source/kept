//! The parts of the macOS clipboard that `arboard` does not reach.
//!
//! `arboard` carries text and images, which is most of what Kept deals with, but it
//! knows nothing about the pasteboard's change counter, the concealed markers
//! password managers set, rich-text flavours or file lists. Those live on
//! `NSPasteboard` itself, so they are reached in these few calls rather than by
//! reimplementing the whole surface.

use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{NSPasteboard, NSPasteboardWriting, NSWorkspace};
use objc2_foundation::{NSArray, NSString, NSURL};

/// The pasteboard types the system defines, spelled out because they are plain
/// strings on the wire and that is how they are looked up.
const TYPE_FILE_URL: &str = "public.file-url";
const TYPE_RTF: &str = "public.rtf";
const TYPE_HTML: &str = "public.html";
const TYPE_TEXT: &str = "public.utf8-plain-text";

/// Set by 1Password, Bitwarden and KeePassXC for a copy they do not want recorded:
/// the macOS answer to Windows' `ExcludeClipboardContentFromMonitorProcessing`.
const CONCEALED: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

fn pasteboard() -> Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

/// The pasteboard's change counter: it moves on every copy, and reading it costs
/// nothing, so the 350 ms poll never has to read content to notice a change.
pub fn sequence_number() -> u32 {
    pasteboard().changeCount().max(0) as u32
}

/// Whether the copy was marked as one an app does not want watched.
pub fn opt_out() -> bool {
    let Some(types) = pasteboard().types() else {
        return false;
    };
    types
        .iter()
        .any(|kind| CONCEALED.contains(&kind.to_string().as_str()))
}

fn string_for_type(kind: &str) -> Option<String> {
    let value = pasteboard().stringForType(&NSString::from_str(kind))?;
    let value = value.to_string();
    (!value.trim().is_empty()).then_some(value)
}

/// The HTML and RTF a text copy carried, so a rich paste can replay them.
pub fn rich_text() -> (Option<String>, Option<String>) {
    (string_for_type(TYPE_HTML), string_for_type(TYPE_RTF))
}

/// The HTML half alone, for the animated-image copy: the file and its `<img>` are
/// published together and only the HTML says which.
pub fn motion_html() -> Option<String> {
    string_for_type(TYPE_HTML)
}

/// Paths of a file-list copy, in the order the Finder put them on the pasteboard.
pub fn file_list() -> Option<Vec<String>> {
    let items = pasteboard().pasteboardItems()?;
    let mut paths = Vec::new();
    for item in items.iter() {
        let Some(value) = item.stringForType(&NSString::from_str(TYPE_FILE_URL)) else {
            continue;
        };
        if let Some(path) = url_to_path(&value.to_string()) {
            paths.push(path);
        }
    }
    (!paths.is_empty()).then_some(paths)
}

/// Turns a `file://` URL into the path Finder and the shell use.
fn url_to_path(url: &str) -> Option<String> {
    let rest = url.strip_prefix("file://")?;
    // The authority is empty for local files, so the first `/` starts the path.
    let path = rest.find('/').map(|index| &rest[index..])?;
    let decoded = crate::clipboard::percent_decode(path);
    let decoded = decoded.strip_suffix('/').unwrap_or(&decoded).to_string();
    (!decoded.is_empty()).then_some(decoded)
}

/// Publishes text, plus the HTML and RTF a rich copy carried, in one session.
pub fn write_text(text: &str, html: Option<&str>, rtf: Option<&str>) -> bool {
    let pasteboard = pasteboard();
    pasteboard.clearContents();
    let mut written =
        pasteboard.setString_forType(&NSString::from_str(text), &NSString::from_str(TYPE_TEXT));
    for (kind, value) in [(TYPE_HTML, html), (TYPE_RTF, rtf)] {
        let Some(value) = value.filter(|value| !value.trim().is_empty()) else {
            continue;
        };
        written &=
            pasteboard.setString_forType(&NSString::from_str(value), &NSString::from_str(kind));
    }
    written
}

/// Puts a list of files on the pasteboard as file URLs, so Finder, chat apps and
/// editors paste them as files rather than as their paths.
pub fn write_files(paths: &[String]) -> bool {
    let pasteboard = pasteboard();
    pasteboard.clearContents();
    pasteboard.writeObjects(&file_objects(paths))
}

/// Publishes a file and a line of text in one session: the file for image-aware
/// targets, the line for everything else.
pub fn write_file_and_text(path: &str, text: &str) -> bool {
    let pasteboard = pasteboard();
    pasteboard.clearContents();
    pasteboard.writeObjects(&file_objects(&[path.to_string()]))
        && pasteboard.setString_forType(&NSString::from_str(text), &NSString::from_str(TYPE_TEXT))
}

fn file_objects(paths: &[String]) -> Retained<NSArray<ProtocolObject<dyn NSPasteboardWriting>>> {
    let urls: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = paths
        .iter()
        .map(|path| {
            ProtocolObject::from_retained(NSURL::fileURLWithPath(&NSString::from_str(path)))
        })
        .collect();
    NSArray::from_retained_slice(&urls)
}

/// The process id of the app in front, which is what auto-paste reactivates.
///
/// macOS has no window handle to remember: reactivating the application brings
/// back whichever window it was showing, and a synthesised keystroke goes to
/// whatever is frontmost when it arrives.
pub fn frontmost_pid() -> Option<i32> {
    let workspace = NSWorkspace::sharedWorkspace();
    let app = workspace.frontmostApplication()?;
    Some(app.processIdentifier())
}

/// The bundle identifier of the app in front, which is what the ignore-list is
/// matched against. Falls back to the display name for anything unsigned.
pub fn frontmost_app() -> Option<String> {
    let workspace = NSWorkspace::sharedWorkspace();
    let app = workspace.frontmostApplication()?;
    if let Some(bundle) = app.bundleIdentifier() {
        let bundle = bundle.to_string();
        if !bundle.is_empty() {
            return Some(bundle);
        }
    }
    app.localizedName().map(|name| name.to_string())
}
